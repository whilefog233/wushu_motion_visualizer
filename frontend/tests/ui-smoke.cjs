const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright')
;(async () => {
 const browser = await chromium.launch({channel:'chrome',headless:true})
 const page = await browser.newPage({viewport:{width:1680,height:1050}})
 const errors=[]
 page.on('pageerror',e=>errors.push(e.message))
 const base=process.env.KUNGFU_TEST_URL || 'http://127.0.0.1:8000'
 const out=path.resolve('docs/ui-verification')
 fs.mkdirSync(out,{recursive:true})
 try {
  await page.goto(base)
  await page.getByRole('heading',{name:'武术 AI 教练系统'}).waitFor()
  assert.equal(await page.locator('.video-viewport canvas').count(),0)
  assert.equal(await page.locator('.metric-value').first().innerText(),'—°')
  await page.getByRole('tab',{name:'AI 建议'}).click()
  assert.match(await page.getByRole('tabpanel').innerText(),/暂无/)
  await page.getByRole('tab',{name:'姿态分析'}).click()
  await page.screenshot({path:path.join(out,'empty-desktop.png'),fullPage:true})
  const list=await (await page.request.get(base+'/api/v1/analyses')).json()
  const items=list.analyses.filter(x=>x.status==='COMPLETED')
  const summaries=await Promise.all(items.map(async x=>({id:x.analysis_id,...await(await page.request.get(base+'/api/v1/analyses/'+x.analysis_id)).json()})))
  const landscape=summaries.find(x=>x.video.width>x.video.height)
  const portrait=summaries.find(x=>x.video.height>x.video.width)
  assert(landscape&&portrait,'Need real landscape and portrait analyses')
  for (const [name,item] of [['landscape',landscape],['portrait',portrait]]) {
   await page.goto(base+'/?id='+item.id)
   await page.locator('.thumbnail').first().waitFor()
   await page.waitForFunction(()=>document.querySelector('video')?.readyState>=2)
   const geometry=await page.locator('.video-viewport').evaluate(el=>{
    const v=el.querySelector('video'),c=el.querySelector('canvas')
    return {vw:v.videoWidth,vh:v.videoHeight,cw:c.width,ch:c.height,videoFit:getComputedStyle(v).objectFit,canvasFit:getComputedStyle(c).objectFit,vRect:v.getBoundingClientRect().toJSON(),cRect:c.getBoundingClientRect().toJSON()}
   })
   assert(Math.abs(geometry.vw/geometry.vh-geometry.cw/geometry.ch)<.01)
   assert.equal(geometry.videoFit,'contain');assert.equal(geometry.canvasFit,'contain')
   assert.equal(geometry.vRect.width,geometry.cRect.width);assert.equal(geometry.vRect.height,geometry.cRect.height)
   const thumb=page.locator('.thumbnail').nth(3)
   const frame=Number((await thumb.getAttribute('aria-label')).match(/\d+/)[0])
   await thumb.click()
   await page.waitForFunction(f=>document.querySelector('.frame-overlay')?.textContent.includes('帧 #'+f+' '),frame)
   const csv=await(await page.request.get(base+'/api/v1/analyses/'+item.id+'/files/metrics.csv')).text()
   const lines=csv.trim().split(/\r?\n/),headers=lines[0].split(',')
   const row=lines.slice(1).map(x=>x.split(',')).find(x=>Number(x[headers.indexOf('frame_index')])===frame)
   const expected=Number(row[headers.indexOf('left_knee_angle')]).toFixed(1)
   assert.match(await page.locator('.core-grid .metric-value').first().innerText(),new RegExp(expected.replace('.','\\.')))
   await page.getByRole('button',{name:'∠ 角度：关'}).click()
   const nonempty=()=>page.locator('.video-viewport canvas').evaluate(c=>c.getContext('2d').getImageData(0,0,c.width,c.height).data.some((v,i)=>i%4===3&&v>0))
   assert(await nonempty(),'Real skeleton must paint')
   await page.screenshot({path:path.join(out,name+'-desktop.png'),fullPage:true})
   await page.getByRole('button',{name:'◎ 骨架：开'}).click()
   assert.equal(await nonempty(),false)
   await page.getByRole('button',{name:'◎ 骨架：关'}).click()
   assert(await nonempty())
   await page.getByRole('button',{name:'下一帧',exact:true}).click()
   await page.waitForFunction(f=>document.querySelector('.frame-overlay').textContent.includes('帧 #'+f+' '),frame+1)
   await page.getByRole('button',{name:'上一帧',exact:true}).click()
   await page.waitForFunction(f=>document.querySelector('.frame-overlay').textContent.includes('帧 #'+f+' '),frame)
   await page.getByLabel('播放速度').selectOption('0.5')
   assert.equal(await page.locator('video').evaluate(v=>v.playbackRate),.5)
   await page.getByRole('button',{name:'播放',exact:true}).click()
   await page.waitForFunction(f=>Number(document.querySelector('.frame-overlay').textContent.match(/#(\d+)/)[1])>f+4,frame)
   await page.getByRole('button',{name:'暂停',exact:true}).click()
   for(const name of ['发力链诊断','肌肉分析','技术对比','AI 建议','姿态分析']) {
    await page.getByRole('tab',{name,exact:true}).click()
    assert((await page.getByRole('tabpanel').innerText()).trim().length>10)
   }
   const link=page.locator('.export-links a').filter({hasText:'运动指标 CSV'})
   assert.equal((await page.request.get(base + await link.getAttribute('href'))).status(),200)
   await page.setViewportSize({width:390,height:844})
   await page.screenshot({path:path.join(out,name+'-mobile.png'),fullPage:true})
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile must not overflow horizontally')
   await page.setViewportSize({width:1680,height:1050})
   console.log(name+': true video + contain geometry + frame/metric sync + skeleton/angle toggles + stepping + playback + five tabs + CSV + mobile PASS')
  }
  assert.deepEqual(errors,[])
  console.log('Browser errors: 0. All checks passed. Screenshots: '+out)
 } finally { await browser.close() }
})().catch(e=>{console.error(e);process.exit(1)})

